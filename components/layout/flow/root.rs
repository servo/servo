#[derive(MallocSizeOf)]
pub struct BoxTree {
    /// Contains typically exactly one block-level box, which was generated by the root element.
    /// There may be zero if that element has `display: none`.
    root: BlockFormattingContext,
    /// Whether or not the viewport should be sensitive to scrolling input events in two axes
    pub(crate) viewport_overflow: AxesOverflow,
    /// The style to use for the initial containing block.
    pub(crate) initial_containing_block_style: ServoArc<ComputedValues>,
}

impl BoxTree {
    #[servo_tracing::instrument(name = "Box Tree Construction", skip_all)]
    pub(crate) fn construct(context: &LayoutContext, root_element: ServoLayoutNode<'_>) -> Self {
        let style_for_writing_mode =
            Self::writing_mode_source_style(&context.style_context, root_element);
        let boxes = construct_for_root_element(context, root_element, &style_for_writing_mode);

        // Zero box for `:root { display: none }`, one for the root element otherwise.
        assert!(boxes.len() <= 1);

        let default_style = context
            .style_context
            .stylist
            .device()
            .default_computed_values_arc();
        let initial_containing_block_style = BoxTree::style_with_writing_mode_source_style(
            default_style.clone(),
            &style_for_writing_mode,
        );

        let viewport_overflow = Self::viewport_overflow(root_element, boxes.first());
        let contents = BlockContainer::BlockLevelBoxes(boxes);
        Self {
            root: BlockFormattingContext::from_block_container(
                contents, /* is_table_cell = */ false, /* textarea_size = */ None,
            ),
            // From https://www.w3.org/TR/css-overflow-3/#overflow-propagation:
            // > If visible is applied to the viewport, it must be interpreted as auto.
            // > If clip is applied to the viewport, it must be interpreted as hidden.
            viewport_overflow: viewport_overflow.to_scrollable(),
            initial_containing_block_style,
        }
    }

    /// From <https://drafts.csswg.org/css-writing-modes/#principal-flow>:
    ///
    /// > The principal writing mode of the document is determined by the used
    /// > writing-mode, direction, and text-orientation values of the root element. This
    /// > writing mode is used, for example, to determine the direction of scrolling and
    /// > the default page progression direction.
    /// >
    /// > As a special case for handling HTML documents, if the root element has a body
    /// > child element [HTML] whose display value is not none, the used value of the of
    /// > writing-mode and direction properties on root element are taken from the
    /// > computed writing-mode and direction of the first such child element instead of
    /// > from the root element’s own values. The UA may also propagate the value of
    /// > text-orientation in this manner. Note that this does not affect the computed
    /// > values of writing-mode, direction, or text-orientation of the root element
    /// > itself.
    pub(crate) fn writing_mode_source_style(
        context: &SharedStyleContext,
        root_element: ServoLayoutNode<'_>,
    ) -> ServoArc<ComputedValues> {
        // See the similar check in viewport_overflow. If there's no root box, then there
        // will never be a box for the body either.
        let root_element_style = root_element.style(context);

        // https://drafts.csswg.org/css-display-3/#transformations
        // “'display' of 'contents' computes to 'block' on the root element”
        debug_assert_ne!(*root_element_style.get_display(), StyleDisplay::Contents);

        if *root_element_style.get_display() == StyleDisplay::None {
            return root_element_style;
        }

        // Unlike what the spec implies, we stop iterating when we find the first <body>,
        // even if it's not suitable because it lacks a box. This matches other browsers.
        // See https://github.com/w3c/csswg-drafts/issues/12644
        let Some(body) = root_element.flat_tree_children().find(|child| {
            child
                .as_element()
                .is_some_and(|element| element.is_body_element_of_html_element_root())
        }) else {
            return root_element_style;
        };

        // We only propagate from the <body> if it generates a box. The spec only checks for
        // `display: none`, but Blink and WebKit don't propagate for `display: contents` either.
        // Gecko propagates from the <body> regardless of its `display`.
        // See https://github.com/w3c/csswg-drafts/issues/12643
        let body_style = body.style(context);
        let body_display = body_style.get_display();
        if *body_display == StyleDisplay::Contents || *body_display == StyleDisplay::None {
            return root_element.style(context);
        }
        body_style.clone()
    }

    pub(crate) fn style_with_writing_mode_source_style(
        base_style: ServoArc<ComputedValues>,
        writing_mode_source_style: &ServoArc<ComputedValues>,
    ) -> ServoArc<ComputedValues> {
        if base_style.writing_mode == writing_mode_source_style.writing_mode &&
            base_style.get_direction() == writing_mode_source_style.get_direction() &&
            base_style.get_text_orientation() == writing_mode_source_style.get_text_orientation()
        {
            return base_style;
        }

        let mut new_style = (*base_style).clone();
        let inherited_box = new_style.mutate_inherited_box();
        inherited_box.writing_mode = writing_mode_source_style.get_inherited_box().writing_mode;
        inherited_box.direction = writing_mode_source_style.get_inherited_box().direction;
        inherited_box.text_orientation = writing_mode_source_style
            .get_inherited_box()
            .text_orientation;
        new_style.writing_mode = writing_mode_source_style.writing_mode;
        ServoArc::new(new_style)
    }

    pub(crate) fn writing_mode(&self) -> WritingMode {
        self.initial_containing_block_style.writing_mode
    }

    fn viewport_overflow(
        root_element: ServoLayoutNode<'_>,
        root_box: Option<&ArcRefCell<BlockLevelBox>>,
    ) -> AxesOverflow {
        // From <https://www.w3.org/TR/css-overflow-3/#overflow-propagation>:
        // > UAs must apply the overflow-* values set on the root element to the viewport when the
        // > root element’s display value is not none. However, when the root element is an [HTML]
        // > html element (including XML syntax for HTML) whose overflow value is visible (in both
        // > axes), and that element has as a child a body element whose display value is also not
        // > none, user agents must instead apply the overflow-* values of the first such child
        // > element to the viewport. The element from which the value is propagated must then have a
        // > used overflow value of visible.

        // If there is no root box, the root element has `display: none`, so don't propagate.
        // The spec isn't very clear about what value to use, but the initial value seems fine.
        // See https://github.com/w3c/csswg-drafts/issues/12649
        let Some(root_box) = root_box else {
            return AxesOverflow::default();
        };

        let propagate_from_body = || {
            // Unlike what the spec implies, we stop iterating when we find the first <body>,
            // even if it's not suitable because it lacks a box. This matches other browsers.
            // See https://github.com/w3c/csswg-drafts/issues/12644
            let body = root_element.flat_tree_children().find(|child| {
                child
                    .as_element()
                    .is_some_and(|element| element.is_body_element_of_html_element_root())
            })?;

            // We only propagate from the <body> if it generates a box. The spec only checks for
            // `display: none`, but other browsers don't propagate for `display: contents` either.
            // See https://github.com/w3c/csswg-drafts/issues/12643
            let body_layout_data = body.inner_layout_data()?;
            let mut body_box = body_layout_data.self_box.borrow_mut();
            body_box.as_mut()?.with_base_mut(|base| {
                base.base_fragment_info
                    .flags
                    .insert(FragmentFlags::PROPAGATED_OVERFLOW_TO_VIEWPORT);
                AxesOverflow::from(&*base.style)
            })
        };

        root_box.borrow_mut().with_base_mut(|base| {
            let root_overflow = AxesOverflow::from(&*base.style);
            if root_overflow.x == Overflow::Visible &&
                root_overflow.y == Overflow::Visible &&
                let Some(body_overflow) = propagate_from_body()
            {
                return body_overflow;
            }
            base.base_fragment_info
                .flags
                .insert(FragmentFlags::PROPAGATED_OVERFLOW_TO_VIEWPORT);
            root_overflow
        })
    }
}

fn construct_for_root_element(
    context: &LayoutContext,
    root_element: ServoLayoutNode<'_>,
    style_for_writing_mode: &ServoArc<ComputedValues>,
) -> Vec<ArcRefCell<BlockLevelBox>> {
    let root_style = BoxTree::style_with_writing_mode_source_style(
        root_element.style(&context.style_context),
        style_for_writing_mode,
    );
    let info = NodeAndStyleInfo::new(root_element, root_style);
    let box_style = info.style.get_box();

    let display_inside = match Display::from(box_style.display) {
        Display::None => return Vec::new(),
        Display::Contents => {
            // Unreachable because the style crate adjusts the computed values:
            // https://drafts.csswg.org/css-display-3/#transformations
            // “'display' of 'contents' computes to 'block' on the root element”
            unreachable!()
        },
        // The root element is blockified, ignore DisplayOutside
        Display::GeneratingBox(display_generating_box) => display_generating_box.display_inside(),
    };

    let contents = Contents::for_element(root_element, context);

    let propagated_data = PropagatedBoxTreeData::default();
    let root_box = if box_style.position.is_absolutely_positioned() {
        BlockLevelBox::OutOfFlowAbsolutelyPositionedBox(ArcRefCell::new(
            AbsolutelyPositionedBox::construct(context, &info, display_inside, contents),
        ))
    } else if box_style.float.is_floating() {
        BlockLevelBox::OutOfFlowFloatBox(FloatBox::construct(
            context,
            &info,
            display_inside,
            contents,
            propagated_data,
        ))
    } else {
        BlockLevelBox::Independent(IndependentFormattingContext::construct(
            context,
            &info,
            display_inside,
            contents,
            propagated_data,
        ))
    };

    let root_box = ArcRefCell::new(root_box);
    root_element
        .box_slot()
        .set(LayoutBox::BlockLevel(root_box.clone()));
    vec![root_box]
}

impl BoxTree {
    #[servo_tracing::instrument(name = "Fragment Tree Construction", skip_all)]
    pub(crate) fn layout(
        &self,
        layout_context: &LayoutContext,
        viewport: UntypedSize2D<Au>,
    ) -> FragmentTree {
        let physical_containing_block: Rect<Au, CSSPixel> =
            PhysicalSize::from_untyped(viewport).into();

        let initial_containing_block = DefiniteContainingBlock {
            size: LogicalVec2::from_physical_size(
                &physical_containing_block.size,
                self.initial_containing_block_style.writing_mode,
            ),
            style: &self.initial_containing_block_style,
        };

        let mut positioning_context = PositioningContext::default();
        let independent_layout = self.root.layout(
            layout_context,
            &mut positioning_context,
            &(&initial_containing_block).into(),
            &initial_containing_block.size.block.into(),
            None,
        );

        let mut root_fragments = independent_layout.fragments;

        // Zero box for `:root { display: none }`, one for the root element otherwise.
        assert!(root_fragments.len() <= 1);

        // There may be more fragments at the top-level
        // (for positioned boxes whose containing is the initial containing block)
        // but only if there was one fragment for the root element.
        positioning_context.layout_initial_containing_block_children(
            layout_context,
            &initial_containing_block,
            &mut root_fragments,
        );

        let viewport_scroll_sensitivity = AxesScrollSensitivity {
            x: self.viewport_overflow.x.into(),
            y: self.viewport_overflow.y.into(),
        };

        FragmentTree::new(
            root_fragments,
            physical_containing_block,
            viewport_scroll_sensitivity,
        )
    }
}
