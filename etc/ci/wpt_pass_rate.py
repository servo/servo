"""
WPT Pass Rate Baseline Calculator and Reporter.

Calculates the actual pass rate and failure distribution from either:
1. WPT run output logs (structured JSON / raw logs from `mach test-wpt`), or
2. The checked-in WPT expectation metadata (`tests/wpt/meta/**/*.ini`).

Produces an honest pass-rate baseline (JSON) and markdown summary without
modifying test expectations.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections import Counter
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional


def analyze_meta_directory(meta_dir: str) -> Dict[str, Any]:
    """Analyze the tests/wpt/meta directory for expectation statistics."""
    counts: Counter[str] = Counter()
    per_suite_counts: Dict[str, Counter[str]] = {}
    total_files = 0

    if not os.path.exists(meta_dir):
        raise FileNotFoundError(f"Meta directory not found: {meta_dir}")

    for root, _, files in os.walk(meta_dir):
        rel = os.path.relpath(root, meta_dir)
        suite = rel.split(os.sep)[0] if rel != "." else "root"
        if suite not in per_suite_counts:
            per_suite_counts[suite] = Counter()

        for f in files:
            if f.endswith(".ini"):
                total_files += 1
                file_path = os.path.join(root, f)
                try:
                    with open(file_path, "r", encoding="utf-8", errors="ignore") as fh:
                        for line in fh:
                            line = line.strip()
                            if line.startswith("expected:"):
                                val = line.split(":", 1)[1].strip()
                                # Clean up conditional expectations if any
                                if "if " in val:
                                    val = val.split("if ")[0].strip()
                                counts[val] += 1
                                per_suite_counts[suite][val] += 1
                except Exception as e:
                    print(f"Warning: failed to read {file_path}: {e}", file=sys.stderr)

    # In WPT meta expectations, files list known non-passing tests or non-default expectations.
    # Total recorded expectations:
    total_entries = sum(counts.values())

    return {
        "source": "meta_expectations",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "total_meta_files": total_files,
        "total_expectation_entries": total_entries,
        "counts": dict(counts.most_common()),
        "top_suites": {
            suite: dict(cnt.most_common(5))
            for suite, cnt in sorted(
                per_suite_counts.items(),
                key=lambda x: sum(x[1].values()),
                reverse=True,
            )[:20]
        },
    }


def analyze_log_files(log_dir: str) -> Dict[str, Any]:
    """Parse raw / structured WPT log files generated by `mach test-wpt`."""
    counts: Counter[str] = Counter()
    total_tests = 0

    if not os.path.exists(log_dir):
        raise FileNotFoundError(f"Log directory not found: {log_dir}")

    for root, _, files in os.walk(log_dir):
        for f in files:
            if f.endswith(".log") or f.endswith(".json"):
                path = os.path.join(root, f)
                try:
                    with open(path, "r", encoding="utf-8", errors="ignore") as fh:
                        for line in fh:
                            line = line.strip()
                            if not line:
                                continue
                            try:
                                entry = json.loads(line)
                                action = entry.get("action")
                                if action in ("test_status", "test_end"):
                                    status = entry.get("status")
                                    if status:
                                        counts[status] += 1
                                        total_tests += 1
                            except json.JSONDecodeError:
                                # Not JSON line, check for raw token patterns
                                for status in ("PASS", "FAIL", "TIMEOUT", "ERROR", "NOTRUN", "CRASH"):
                                    if f" {status} " in line or line.startswith(f"{status}:"):
                                        counts[status] += 1
                                        total_tests += 1
                                        break
                except Exception as e:
                    print(f"Warning: failed to read {path}: {e}", file=sys.stderr)

    passes = counts.get("PASS", 0) + counts.get("OK", 0)
    pass_rate = (passes / total_tests * 100.0) if total_tests > 0 else 0.0

    return {
        "source": "run_logs",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "total_results": total_tests,
        "pass_count": passes,
        "pass_rate_percent": round(pass_rate, 2),
        "counts": dict(counts.most_common()),
    }


def generate_markdown_report(data: Dict[str, Any]) -> str:
    lines = [
        "# WPT Conformance Pass-Rate Baseline Report",
        "",
        f"**Generated:** {data.get('timestamp', 'unknown')} | **Source:** `{data.get('source', 'unknown')}`",
        "",
    ]

    if data.get("source") == "run_logs":
        lines.extend([
            "## Summary",
            "",
            f"- **Total Tests Evaluated:** {data.get('total_results', 0):,}",
            f"- **Passing (PASS/OK):** {data.get('pass_count', 0):,}",
            f"- **Honest Pass Rate:** **{data.get('pass_rate_percent', 0.0)}%**",
            "",
            "### Detailed Outcomes",
            "",
            "| Status | Count | Percentage |",
            "|---|---:|---:|",
        ])
        total = data.get("total_results", 1) or 1
        for status, count in data.get("counts", {}).items():
            pct = count / total * 100.0
            lines.append(f"| `{status}` | {count:,} | {pct:.2f}% |")
    else:
        total = data.get("total_expectation_entries", 0)
        lines.extend([
            "## Expectations Baseline (Static tree analysis)",
            "",
            f"- **Total Expectation Files:** {data.get('total_meta_files', 0):,}",
            f"- **Total Non-Default Entries:** {total:,}",
            "",
            "### Outcome Breakdown in `tests/wpt/meta`",
            "",
            "| Status | Entry Count | Share of Failures |",
            "|---|---:|---:|",
        ])
        for status, count in data.get("counts", {}).items():
            pct = count / total * 100.0 if total > 0 else 0.0
            lines.append(f"| `{status}` | {count:,} | {pct:.2f}% |")

        lines.extend([
            "",
            "### Top Test Suites with Non-Pass Entries",
            "",
            "| Test Suite | Top Outcomes |",
            "|---|---|",
        ])
        for suite, counts in data.get("top_suites", {}).items():
            summary = ", ".join(f"{k}: {v:,}" for k, v in counts.items())
            lines.append(f"| `{suite}` | {summary} |")

    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="WPT Pass Rate Baseline Tool")
    parser.add_argument("--meta-dir", default="tests/wpt/meta", help="Path to tests/wpt/meta directory")
    parser.add_argument("--logs-dir", help="Path to directory containing WPT run logs")
    parser.add_argument("--output-json", help="Path to write baseline JSON output")
    parser.add_argument("--output-markdown", help="Path to write markdown report")
    args = parser.parse_args()

    if args.logs_dir and os.path.exists(args.logs_dir):
        data = analyze_log_files(args.logs_dir)
    else:
        data = analyze_meta_directory(args.meta_dir)

    report_md = generate_markdown_report(data)

    if args.output_markdown:
        with open(args.output_markdown, "w", encoding="utf-8") as fh:
            fh.write(report_md)
        print(f"Wrote markdown report to {args.output_markdown}")
    else:
        print(report_md)

    if args.output_json:
        with open(args.output_json, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=2)
        print(f"Wrote baseline JSON to {args.output_json}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
