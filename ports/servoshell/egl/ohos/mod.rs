/// 启动以来的日志环形缓冲，供「设置 → 调试与反馈」查看与复制。
/// 设备上拿不到 hilog 时，这是唯一的取证手段。
const LOG_CAP: usize = 3000;
static LOG_RING: LazyLock<Mutex<VecDeque<String>>> =
    LazyLock::new(|| Mutex::new(VecDeque::with_capacity(LOG_CAP)));

fn push_log_line(line: String) {
    let mut ring = match LOG_RING.lock() {
        Ok(ring) => ring,
        Err(_) => return,
    };
    if ring.len() >= LOG_CAP {
        ring.pop_front();
    }
    ring.push_back(line);
}

fn log_timestamp() -> String {
    static START: LazyLock<Instant> = LazyLock::new(Instant::now);
    let elapsed = START.elapsed();
    let ms = elapsed.as_millis();
    format!("{:>4}.{:03}s", ms / 1000, ms % 1000)
}

struct RingLogger;

impl log::Log for RingLogger {
    fn enabled(&self, metadata: &log::Metadata<'_>) -> bool {
        (*LOGGER).enabled(metadata)
    }

    fn log(&self, record: &log::Record<'_>) {
        (*LOGGER).log(record);
        push_log_line(format!(
            "{} {:<5} {}: {}",
            log_timestamp(),
            record.level(),
            record.target(),
            record.args()
        ));
    }

    fn flush(&self) {
        (*LOGGER).flush();
    }
}

static RING_LOGGER: RingLogger = RingLogger;

#[napi(js_name = "debugLogs")]
pub fn debug_logs() -> String {
    match LOG_RING.lock() {
        Ok(ring) => ring.iter().cloned().collect::<Vec<String>>().join("\n"),
        Err(_) => String::new(),
    }
}

/// ArkTS 侧的日志（hilog 那些）也写进同一份环形缓冲，导出时一并带走。
#[napi(js_name = "appendJsLog")]
pub fn append_js_log(line: String) {
    push_log_line(format!("{} JS    servo.ui: {}", log_timestamp(), line));
}

#[napi(js_name = "clearDebugLogs")]
pub fn clear_debug_logs() {
    if let Ok(mut ring) = LOG_RING.lock() {
        ring.clear();
    }
}

fn initialize_logging_once() {
    static ONCE: Once = Once::new();
    ONCE.call_once(|| {
        let max_level = (*LOGGER).filter();
        let r = log::set_logger(&RING_LOGGER).map(|()| log::set_max_level(max_level));
        debug!("Attempted to register the logger: {r:?} and set max level to: {max_level}");
        info!("Servo Register callback called!");

        std::panic::set_hook(Box::new(|info| {
            error!("Panic in Rust code");
            error!("PanicInfo: {info}");
            let msg = match info.payload().downcast_ref::<&'static str>() {
                Some(s) => *s,
                None => match info.payload().downcast_ref::<String>() {
                    Some(s) => &**s,
                    None => "Box<Any>",
                },
            };
            let current_thread = thread::current();
            let name = current_thread.name().unwrap_or("<unnamed>");
            if let Some(location) = info.location() {
                error!(
                    "{} (thread {}, at {}:{})",
                    msg,
                    name,
                    location.file(),
                    location.line()
                );
            } else {
                error!("{} (thread {})", msg, name);
            }

            crate::backtrace::print_ohos();
        }));

        // We only redirect stdout and stderr for non-production builds, since it is
        // only used for debugging purposes. This saves us one thread in production.
        #[cfg(not(servo_production))]
        if let Err(e) = super::log::redirect_stdout_and_stderr() {
            error!("Failed to redirect stdout and stderr to hilog due to: {e:?}");
        }
    });
}

pub fn set_log_filter(filter: Option<&str>) {
    let Some(filter) = filter else {
        debug!("Called ohos::set_log_filter without providing a filter");
        return;
    };

    debug!("Updating log filter to {filter}");
    let mut builder = env_filter::Builder::new();
    let filter = match builder.try_parse(filter) {
        Result::Ok(filter) => filter,
        Result::Err(err) => {
            error!("Failed to parse log filter: {err}");
            return;
        },
    };
    let filter = filter.build();
    (*LOGGER).set_filter(filter);
}

fn register_xcomponent_callbacks(env: &Env, xcomponent: &Object) -> napi_ohos::Result<()> {
    info!("napi_get_named_property call successfull");
    let raw = xcomponent.raw();
    let raw_env = env.raw();
    let mut nativeXComponent: *mut OH_NativeXComponent = core::ptr::null_mut();
    unsafe {
        let res = napi_ohos::sys::napi_unwrap(
            raw_env,
            raw,
            &mut nativeXComponent as *mut *mut OH_NativeXComponent as *mut *mut c_void,
        );
        assert!(res.is_zero());
    }
    info!("Got nativeXComponent!");
    let cbs = Box::new(OH_NativeXComponent_Callback {
        OnSurfaceCreated: Some(on_surface_created_cb),
        OnSurfaceChanged: Some(on_surface_changed_cb),
        OnSurfaceDestroyed: Some(on_surface_destroyed_cb),
        DispatchTouchEvent: Some(on_dispatch_touch_event_cb),
    });
    let res =
        unsafe { OH_NativeXComponent_RegisterCallback(nativeXComponent, Box::leak(cbs) as *mut _) };
    if res != 0 {
        error!("Failed to register callbacks");
    } else {
        info!("Registered callbacks successfully");
    }

    let res = unsafe {
        OH_NativeXComponent_RegisterKeyEventCallback(nativeXComponent, Some(on_dispatch_key_event))
    };
    if res != 0 {
        error!("Failed to register key event callbacks");
    } else {
        debug!("Registered key event callbacks successfully");
    }

    let mouse_cbs = Box::new(OH_NativeXComponent_MouseEvent_Callback {
        DispatchMouseEvent: Some(on_dispatch_mouse_event_cb),
        DispatchHoverEvent: None,
    });
    let res = unsafe {
        OH_NativeXComponent_RegisterMouseEventCallback(
            nativeXComponent,
            Box::leak(mouse_cbs) as *mut _,
        )
    };
    if res != 0 {
        error!("Failed to register mouse event callbacks with {res}");
    } else {
        debug!("Registered mouse event callbacks successfully");
    }

    let res = unsafe {
        OH_NativeXComponent_RegisterUIInputEventCallback(
            nativeXComponent,
            Some(on_axis_event_cb),
            ARKUI_UIINPUTEVENT_TYPE_AXIS,
        )
    };
    if res != 0 {
        // Not fatal: without this callback the app still works, it just cannot scroll with a wheel.
        warn!("Failed to register wheel (axis) event callback with {res}");
    } else {
        debug!("Registered wheel (axis) event callback successfully");
    }
    Ok(())
}

